/**
 * The 22 factor cards (course map, section 4). Each card answers the same eight
 * questions about one thing a bank or the regulator looks at:
 *   1. what it is · 2. why the bank or the regulator cares · 3. how it moves approval
 *   and price, through which mechanism · 4. where the thresholds are, and from what
 *   source · 5. what the client can really change · 6. what the change costs ·
 *   7. a numerical example · 8. how the algorithm uses it.
 *
 * Shown in lessons 4.10 (the client's nine cards) and 4.11 (the other thirteen), and
 * kept for the downloadable appendix. The text of a card shown in 4.10 uses only
 * terms taught up to 4.10; a card shown in 4.11, terms up to 4.11 (the term check
 * reads the lesson pages, so this file keeps the same rule by hand).
 *
 * Labels. Every threshold names its source kind. Every other claim that is not
 * general knowledge carries its label in the sentence: an official rule read only
 * through the team's transcription or a search summary is "לא אומת"; field
 * knowledge names who said it, when, its FK id (research/field-knowledge.md) and
 * "ממתין לאישור אילון"; a Mogi decision names who decided and when. Where nobody
 * gave a number, the card says it is not known, and the question is on the Eylon list.
 *
 * Numbers. The example's teaching inputs are written once, in `example.steps`;
 * every other number of the example is computed from them by src/lib/calc/factors.ts
 * (facts "card.<id>.<name>" in data/lessons/4-10.json and 4-11.json, rechecked by
 * checks/kinds/factors.py). The text shows them through {name} placeholders.
 * Rule values in the text (75%, 50%, 18 months) are the rules themselves, each with its label.
 */
import type { ExampleStep } from "../lib/calc/factors.ts";

export type SourceKind =
  | "עובדה מאומתת"
  | "החלטה של Mogi"
  | "ידע מהשטח"
  | "מחקר / הצעה"
  | "הנחת חישוב"
  | "לא אומת"
  | "ידע מתמטי כללי"
  | "ידע כלכלי כללי";

export type CardGroup = "client" | "deal" | "bank" | "bank_market" | "mix" | "process";

export const GROUP_LABELS: Record<CardGroup, string> = {
  client: "הלקוח",
  deal: "העסקה",
  bank: "הבנק",
  bank_market: "הבנק והשוק",
  mix: "התמהיל",
  process: "התהליך",
};

export interface Threshold {
  /** The threshold, or a plain "no known threshold". */
  text: string;
  kind: SourceKind;
  /** Where it comes from, with its date. */
  source: string;
  /** True when the course does not know, and the question goes to Eylon. */
  open?: boolean;
}

export interface CardSource {
  kind: SourceKind;
  text: string;
  date?: string;
}

export type ValueFormat = "shekels" | "percent" | "number" | "date";

export interface FactorCard {
  /** The card's number in the course map, section 4. */
  n: number;
  id: string;
  title: string;
  group: CardGroup;
  /** The lesson that shows the card. */
  shownIn: "4.10" | "4.11";
  /** Where the topic is taught in depth. */
  taught: string;
  /** The big-picture map node the card belongs to (src/components/big-picture/). */
  node: string;
  what: string;
  why: string;
  effect: string;
  thresholds: Threshold[];
  levers: string;
  cost: string;
  example: {
    steps: ExampleStep[];
    /** How each value is shown. Values without an entry are shown as numbers. */
    formats: Record<string, ValueFormat>;
    /** The example, with {name} where a value goes. */
    text: string;
  };
  algorithm: { text: string; kind: SourceKind };
  sources: CardSource[];
}

